-- 0007 — 계정 처리정지 (2026-08-26)
--
-- 배경: 방침의 「처리정지」 칸이 **로그아웃**을 가리키고 있었다. 로그아웃은 접근 세션을 끊을
-- 뿐이고 계정·단어장·별명·친구 관계·가입 기록은 그대로 남아 친구에게 계속 보인다 —
-- 즉 처리는 하나도 멈추지 않는다. 「멈춘다」고 적어 놓고 안 멈추는 것이 이 칸의 결함이었다.
--
-- 그래서 **정지 여부의 진실 원본을 한 칸**으로 둔다. 상태 표를 따로 만들지 않는 이유는
-- 정지가 두 값(정지됨/아님)뿐이고, 시각 하나면 「언제부터」까지 답하기 때문이다.
--
-- ⚠️ 재실행 가능해야 한다. `ALTER TABLE ADD COLUMN` 은 IF NOT EXISTS 를 못 쓰므로 이 파일은
--    한 번만 적용한다 — 이미 적용됐는지는 `PRAGMA table_info(users)` 로 확인한다
--    (docs/OPS_RUNBOOK.md).
-- ⚠️ 새 표가 아니라 `users` 의 칸이므로 **CASCADE 규칙이 늘지 않는다** — 계정을 지우면
--    이 값도 행과 함께 사라진다(test-migrations 의 전수 검사가 그대로 성립한다).
ALTER TABLE users ADD COLUMN suspended_at INTEGER;
