// 문장 매칭 자체검증. `node scripts/test-match.mjs`
// app.js 실제 buildIndex/matchSentence를 mock 사전으로 검증(로직 중복 없음).
import { loadApp } from "./_app.mjs";

const M = loadApp("buildIndex, matchSentence");

const MOCK = [
  { word: "미안", aliases: [] },
  { word: "년", aliases: ["해"] },
  { word: "사과", aliases: [] },          // 과일
  { word: "죄송하다", aliases: ["사과", "미안하다"] }, // 사죄
  { word: "학교", aliases: [] },
  { word: "사랑", aliases: [] },
  { word: "모두", aliases: ["다"] },       // "다"=모두 별칭(오매칭 유발원)
  { word: "반갑다", aliases: [] },
  { word: "먹", aliases: [] },           // 墨 — 1글자 오매칭 유발원
  { word: "먹다", aliases: ["식사"] },
  { word: "보다", aliases: [] },
  { word: "보고", aliases: [] },       // report (다른 수형)
  { word: "싶다", aliases: [] },
  // 어간이 변하는 활용 — deconjugate 회귀검증용
  { word: "고맙다", aliases: [] },
  { word: "기다리다", aliases: [] },
  { word: "괜찮다", aliases: [] },
  { word: "고프다", aliases: ["배고프다"] },
  // 2026-08-08 활용 규칙 6개용. 실제 사전의 표제어–별칭 관계를 그대로 옮겼다.
  { word: "일어", aliases: [] },            // 일본어 — '일어나'가 여기로 떨어졌던 오매칭 유발원
  { word: "기상", aliases: ["일어나다"] },
  { word: "모르다", aliases: [] },
  { word: "갈증", aliases: ["목마르다"] },
  { word: "배부르다", aliases: [] },
  { word: "화나다", aliases: [] },
  { word: "알다", aliases: [] },
  { word: "지각", aliases: ["늦다", "천천하다"] },
  { word: "많다", aliases: [] },
  { word: "가만히", aliases: ["조용하다"] },
  { word: "안되다", aliases: [] },
  { word: "지다", aliases: [] },            // 지냈어 오매칭 유발원. '지내다'는 사전에 없다(실제로도 없다)
  // 2026-08-08 일상어 감사용. 실제 사전의 표제어 관계를 그대로 옮겼다.
  { word: "미치다", aliases: [] },
  { word: "결혼", aliases: [] },
  { word: "하자", aliases: [] },            // 瑕疵(흠) — '결혼하자'의 뒤가 여기 걸렸던 오매칭 유발원
];
M.buildIndex(MOCK);
const words = (t) => M.matchSentence(t).map((k) => (k.type === "entry" ? k.entries.map((e) => e.word).join("|") : "?" + k.text));

let fail = 0;
const eq = (got, exp, name) => {
  const g = JSON.stringify(got), e = JSON.stringify(exp);
  if (g !== e) { console.error(`FAIL ${name}: ${g} (기대 ${e})`); fail++; }
  else console.log(`OK   ${name}: ${g}`);
};

eq(words("미안해"), ["미안"], "미안해 → 미안(해 흡수, 년 아님)");
eq(words("미안해요"), ["미안"], "미안해요 → 미안");
eq(words("사랑해"), ["사랑"], "사랑해 → 사랑");
eq(words("사과"), ["사과|죄송하다"], "사과 → 과일+사죄 후보 둘");
eq(words("학교에서"), ["학교"], "학교에서 → 학교(에서 흡수)");
eq(words("해"), ["년"], "해 홀로 → 년(어미 흡수는 매칭 뒤에만)");
eq(words("반갑습니다"), ["반갑다"], "반갑습니다 → 반갑다(습니다→다 정규화)");
eq(words("먹다"), ["먹다"], "먹다 → 먹다(墨 '먹' 아님)");
// 문장 안 1글자 매칭 금지. 없으면 잘자=잘하다+사람, 배고파=배+고+파 같은 조각 오답이 난다.
eq(words("먹고"), ["?먹고"], "먹고 → 조각내지 않고 통째로 미지원(1글자 '먹' 금지)");
// 어간이 변하는 활용 — ENDINGS 로는 못 푸는 것들
eq(words("고마워"), ["고맙다"], "고마워 → 고맙다(ㅂ불규칙)");
eq(words("기다려"), ["기다리다"], "기다려 → 기다리다(려→리다)");
eq(words("괜찮아"), ["괜찮다"], "괜찮아 → 괜찮다(아 제거)");
eq(words("배고파"), ["고프다"], "배고파 → 고프다(ㅡ탈락, 배=선박 아님)");
eq(words("사과야"), ["사과|죄송하다"], "사과야 → 사과(야 흡수)");
// "이야"는 일부러 ENDINGS 에 안 넣었다 — 넣으면 '사랑이야기'가 사랑+[이야]+지화'기' 로 깨진다.
eq(words("사랑이야기"), ["사랑", "?이야기"], "사랑이야기 → '이야'를 먹지 않는다");
eq(words("다"), ["모두"], "다 홀로 → 모두(정규화·흡수는 매칭 뒤에만)");
eq(words("보고싶다"), ["보다", "싶다"], "보고싶다 → 보다+싶다(보고=report 아님)");
eq(words("보고싶어요"), ["보다", "싶다"], "보고싶어요 → 보다+싶다");
eq(words("보고"), ["보고"], "보고 홀로 → 보고(report, 고싶 규칙 오작동 없음)");

// ── 2026-08-08 에 넣은 활용 규칙 6개. 전부 "지화로 떨어지던 말"을 사전으로 끌어온 것이다.
//    사전 12,943 표제어 + 일상어 + 문장 15,616 입력을 규칙 전/후로 대조해 **지화가 늘어난 입력 0** 을 확인했다.
eq(words("일어나"), ["기상"], "일어나 → 기상. 안 넣으면 '일어'(일본어)+지화'나' 가 뜬다 ⛔");
eq(words("몰라"), ["모르다"], "몰라 → 모르다(르-불규칙)");
eq(words("목말라"), ["갈증"], "목말라 → 갈증(르-불규칙)");
eq(words("배불러"), ["배부르다"], "배불러 → 배부르다(르-불규칙)");
eq(words("화났어"), ["화나다"], "화났어 → 화나다(ㅆ만 떼고 모음은 어간에 남김)");
eq(words("알았어"), ["알다"], "알았어 → 알다('았'이 통째로 어미)");
eq(words("늦었어"), ["지각"], "늦었어 → 지각[늦다]");
eq(words("많이"), ["많다"], "많이 → 많다(부사 -이)");
eq(words("조용히"), ["가만히"], "조용히 → 가만히[조용하다](부사 -히)");
eq(words("안돼"), ["안되다"], "안돼 → 안되다");

// ⚠️ 과거형에서 **음절을 통째로 떼는 쪽**은 '았/었/였' 일 때만 쓴다.
//    아무 데나 쓰면 지냈어 → '지다'(패배) 가 떠서, 지화로 떨어지던 말이 틀린 수어로 단정된다(⛔).
//    지내다는 사전에 아예 없으므로 여기서 [지다]가 나오면 규칙이 다시 헐거워진 것이다.
if (words("지냈어").includes("지다")) { console.log("FAIL 지냈어 → 지다(패배). 과거형 규칙이 너무 헐겁다"); fail = 1; }

// 활용 후보가 **1글자**로 떨어지면 안 된다. 과거형 규칙이 후보 "다" 를 내면 1글자 표제어
// '다'(=모두)에 걸린다 — 문장 속 1글자 금지(함정 16)를 우회하는 구멍이었다.
// ('았어' 는 그 구멍을 여는 최소 입력이다. 실제로는 '재밌어'가 [모두]로 떴다.)
if (words("았어").includes("모두")) { console.log("FAIL 았어 → [모두]. 활용 후보가 1글자로 떨어졌다"); fail = 1; }

// ── 2026-08-08 일상어 160개를 앱에 먹여 눈으로 훑고 고친 자리. 15,604 입력 전/후 대조에서
//    지화가 늘어난 입력은 0 이었다.
// 과거형 ㅕ 축약: 미쳤어 = 미치+었+어. 사전에 미치다가 **있는데도** 통째로 지화로 떨어졌다.
// (기다려→기다리다 규칙이 ㄹ 에만 하던 일을 자음 전체로 넓힌 것이다.)
eq(words("미쳤어"), ["미치다"], "미쳤어 → 미치다(ㅕ→ㅣ)");
eq(words("미쳤다"), ["미치다"], "미쳤다 → 미치다(과거+종결 '다')");
// 청유 '하자' 를 안 먹으면 뒤가 표제어 하자(瑕疵, 흠)에 걸려 카드가 두 장 뜬다 — ⛔ 위반.
eq(words("결혼하자"), ["결혼"], "결혼하자 → [결혼] 한 장. 하자(瑕疵)가 붙으면 안 된다");
eq(words("하자"), ["하자"], "하자 홀로 → 하자. 어미 흡수는 매칭 뒤에만 돈다");

process.exit(fail ? 1 : 0);
